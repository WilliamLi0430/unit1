/* Each game has 10 frames.In each frame, you get two rolls 
to knock down 10 pins (except the 10th frame).
Each pin you knock down is worth one point.

If you do not knock down all 10 pins after two rolls, it is an open frame.
You simply add the pins from both rolls together for your score.
Example: If you hit 6 pins on the first roll and 2 on the second, 
you get 8 points for that frame.

A spare happens when you knock down all 10 pins using two rolls. 
It is marked with a slash (/).
You get 10 points plus a bonus equal to the number of pins 
you knock down on your very next roll.
Example: If you get a spare, and then knock down 7 pins on your first 
roll of the next frame, that spare frame is worth 17 points (10 + 7).

A strike happens when you knock down all 10 pins on your first roll.
It is marked with an X.
You get 10 points plus a bonus equal to the total pins you knock down 
on your next two rolls.
Example: If you roll a strike, and then score 8 pins and 1 pin on your 
next two rolls, that strike frame is worth 19 points (10 + 8 + 1).
Getting multiple strikes in a row stacks your bonus points, which 
is how players reach a 300 maximum score (a perfect game of 12 strikes).

If you roll a strike or a spare in the 10th and final frame, you get 
extra rolls to complete your bonus points.
A spare earns you one extra roll, while a strike earns you two extra rolls. */